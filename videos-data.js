  function setupVideoModal() {
    const modal = document.getElementById('videoModal');
    const closeBtn = document.getElementById('videoModalClose');
    const prevBtn = document.getElementById('videoModalPrev');
    const nextBtn = document.getElementById('videoModalNext');

    if (closeBtn) closeBtn.addEventListener('click', closeVideoModal);
    if (modal) {
      modal.addEventListener('click', (e) => {
        if (e.target === modal || e.target.classList.contains('video-modal-backdrop')) {
          closeVideoModal();
        }
      });
    }

    if (prevBtn) {
      prevBtn.addEventListener('click', () => {
        if (activePlaylist.length <= 1) return;
        currentVideoIndex = (currentVideoIndex - 1 + activePlaylist.length) % activePlaylist.length;
        loadModalVideo(activePlaylist[currentVideoIndex]);
      });
    }

    if (nextBtn) {
      nextBtn.addEventListener('click', () => {
        if (activePlaylist.length <= 1) return;
        currentVideoIndex = (currentVideoIndex + 1) % activePlaylist.length;
        loadModalVideo(activePlaylist[currentVideoIndex]);
      });
    }

    document.addEventListener('keydown', (e) => {
      const m = document.getElementById('videoModal');
      if (!m || !m.classList.contains('active')) return;

      if (e.key === 'Escape') {
        closeVideoModal();
      } else if (e.key === 'ArrowLeft') {
        if (prevBtn) prevBtn.click();
      } else if (e.key === 'ArrowRight') {
        if (nextBtn) nextBtn.click();
      }
    });
  }

