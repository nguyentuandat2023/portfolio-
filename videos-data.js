      ytLink.href = video.youtubeUrl;
      const isGd = video.platform === 'gdrive';
      ytLink.title = isGd ? (isVi ? 'Mở trên Google Drive' : 'Open in Google Drive') : (isVi ? 'Mở trên YouTube' : 'Open in YouTube');
